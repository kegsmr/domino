"""The tables of RESULTS.md, and the charts, from a results JSON."""

import re
from pathlib import Path


BEGIN = "<!-- tables:begin (generated by run.py; edit the text around them, not inside) -->"
END = "<!-- tables:end -->"

# The reference categorical palette, in fixed order (Domino first)
COLORS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]


def ms(value, digits=0):

	if value is None:
		return "–"

	return f"{value:,.{digits}f}"


def cell(item, scale=1, digits=0):
	"""median (p95) of a summary."""

	if not item:
		return "–"

	return f"{ms(item['median'] * scale, digits)} ({ms(item['p95'] * scale, digits)})"


def kb(value):

	return "–" if value is None else f"{value / 1000:,.1f}"


def table(header, rows):

	lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(header))) + "|"]
	lines += ["| " + " | ".join(str(part) for part in row) + " |" for row in rows]

	return "\n".join(lines)


def tables(results, json_name):

	fw = results["frameworks"]
	names = list(fw)
	label = lambda name: fw[name]["label"]
	env = results["environment"]
	out = []

	out.append(f"Run {env['date']} ({results['minutes']} min), raw data: [results/{json_name}](results/{json_name}).")
	out.append("")
	load = results["load"]
	out.append(f"Machine: {env['cores']} cores ({env['cpu']}), {env['memory_gb']} GB, {env['os']}; Chromium {env['chromium']} "
		f"(Playwright {env['playwright']}, headless), Python {env['python']}, Node {env['node']}. "
		f"Load average (1/5/15 min) at the start {'/'.join(f'{x:.1f}' for x in load['start'])}, at the end "
		f"{'/'.join(f'{x:.1f}' for x in load['end'])}: other jobs shared the machine.")
	out.append("")
	out.append(table(["Framework", "Versions"], [[label(name), ", ".join(f"{k} {v}" for k, v in fw[name]["versions"].items())] for name in names]))
	if results.get("skipped"):
		out.append("")
		out.append("Not measured: " + "; ".join(f"{name}: {why}" for name, why in results["skipped"].items()))

	# Page weight
	out.append("\n### Page weight (cold load, KB)\n")
	out.append("*As sent*: HTTP bytes on the wire, headers included, compressed only if the server compresses. *gzip*: every "
		"HTTP body gzipped at level 6, the same for everyone. *WS*: WebSocket payload received while loading (uncompressed; "
		"some frameworks send the page's data this way).\n")
	rows = []
	for name in names:
		weight = fw[name].get("page_weight", {})
		row = [label(name)]
		for app in ("counter", "todo", "chat"):
			item = weight.get(app)
			if not item:
				row += ["–"] * 3
				continue
			row += [kb(item["transferred_bytes"]["median"]), kb(item["gzip_bytes"]["median"]), kb(item["ws_received_bytes"]["median"])]
		encodings = sorted({value for app in weight.values() for value in app["encodings"].values()})
		row.append(", ".join(encodings))
		rows.append(row)
	out.append(table(["Framework", "Counter as sent", "gzip", "WS", "Todo (1,000) as sent", "gzip", "WS", "Chat as sent", "gzip", "WS",
		"Content-Encoding seen"], rows))

	# First load
	out.append("\n### First load (ms, median (p95))\n")
	out.append("From navigation start: first contentful paint, and *interactive*: the first click that changes the page "
		"(clicking every 100 ms until one does; counter +1, todo toggle).\n")
	rows = []
	for name in names:
		loads = fw[name].get("first_load", {})
		row = [label(name)]
		for rtt in ("0", "100"):
			data = loads.get(rtt, {})
			row += [cell(data.get("counter", {}).get("fcp_ms")), cell(data.get("counter", {}).get("interactive_ms")),
				cell(data.get("todo", {}).get("fcp_ms")), cell(data.get("todo", {}).get("interactive_ms"))]
		rows.append(row)
	out.append(table(["Framework", "Counter FCP @0", "Counter interactive @0", "Todo FCP @0", "Todo interactive @0",
		"Counter FCP @100", "Counter interactive @100", "Todo FCP @100", "Todo interactive @100"], rows))

	# Click latency
	out.append("\n### Click → DOM updated (ms, median (p95))\n")
	out.append("From the click's first input event to the DOM showing the result, with 0, 100 and 300 ms round trip added "
		"by a TCP proxy for every framework alike. *Counter*: UI-only state. *Toggle*: a todo item's checkbox, data the "
		"server keeps (React updates optimistically, as is usual). *Add*: a new todo, shown once the server has it.\n")
	rtts = sorted({rtt for name in names for rtt in fw[name].get("interactions", {})}, key=int)
	rows = []
	for name in names:
		inter = fw[name].get("interactions", {})
		row = [label(name)]
		for kind in ("counter", "toggle", "add"):
			row += [cell(inter.get(rtt, {}).get(kind), digits=0 if rtt != "0" else 1) for rtt in rtts]
		rows.append(row)
	out.append(table(["Framework"] + [f"{kind} @{rtt}" for kind in ("Counter", "Toggle", "Add") for rtt in rtts], rows))

	# CPU and bytes per interaction
	out.append("\n### Server cost per interaction (at 0 ms)\n")
	out.append("Server CPU (all its processes and threads, from /proc schedstat, less what it spends idle over the same time) "
		"and bytes on the wire (HTTP as transferred, WebSocket payload uncompressed) per interaction.\n")
	rows = []
	for name in names:
		zero = fw[name].get("interactions", {}).get("0", {})
		row = [label(name)]
		for kind in ("counter", "toggle", "add"):
			row += [ms(zero.get(kind + "_cpu_ms"), 2), ms(zero.get(kind + "_bytes"))]
		row.append(ms((sum(fw[name].get("idle_cpu", [0])) / max(1, len(fw[name].get("idle_cpu", [0])))) * 1000, 1))
		rows.append(row)
	out.append(table(["Framework", "Counter CPU ms", "bytes", "Toggle CPU ms", "bytes", "Add CPU ms", "bytes", "Idle CPU ms/s"], rows))

	# Fan-out
	if any("fanout" in fw[name] for name in names):
		counts = sorted({count for name in names for count in fw[name].get("fanout", {})}, key=int)
		out.append("\n### Chat fan-out\n")
		out.append("*Latency*: from a Send click in one tab to the message in every tab (the sender's too), ms, median (p95) "
			"over all deliveries of 10 messages. *Throughput*: another user posts up to 200 messages back to back "
			"(each POST waiting for its answer, at most 20 s of posting) until every tab shows the last; messages per "
			"second, and server CPU ms per message.\n")
		rows = []
		for name in names:
			fan = fw[name].get("fanout", {})
			row = [label(name)]
			for count in counts:
				row.append(cell(fan.get(count, {}).get("delivery_ms")))
			for count in counts:
				through = fan.get(count, {}).get("throughput")
				row.append(f"{through['messages_per_s']:,.0f} ({through['server_cpu_ms_per_message']:,.1f} ms)" if through else "–")
			rows.append(row)
		out.append(table(["Framework"] + [f"Latency, {count} tabs" for count in counts] + [f"Msg/s, {count} tabs" for count in counts], rows))

	# Memory
	if any("idle_memory" in fw[name] for name in names):
		counts = sorted({count for name in names for count in fw[name].get("idle_memory", {})}, key=int)
		out.append("\n### Server memory per idle connected tab\n")
		out.append("The chat open (and live: a message reached every tab) in N tabs; the server's memory (PSS of all its "
			"processes) after, less before, divided by N.\n")
		rows = []
		for name in names:
			mem = fw[name].get("idle_memory", {})
			rows.append([label(name), ms(fw[name].get("server_baseline_mb"), 0)]
				+ [ms(mem.get(count, {}).get("per_tab_kb")) for count in counts])
		out.append(table(["Framework", "Server at rest, MB"] + [f"KB per tab, {count} tabs" for count in counts], rows))

	# Lines of code
	out.append("\n### Lines of app code\n")
	out.append("Non-blank, non-comment lines (cloc's rules), benchmark hooks left out; *shared* is setup every app needs. "
		"Domino's code style puts each child list's brackets on lines of their own, which costs it lines.\n")
	rows = [[fw[name]["label"]] + [results["loc"][name][app] for app in ("counter", "todo", "chat", "shared", "total")]
		for name in names if name in results["loc"]]
	out.append(table(["Framework", "Counter", "Todo", "Chat", "Shared", "Total"], rows))

	return "\n".join(out)


def write(results, path, results_dir, json_name):

	generated = tables(results, json_name)
	text = path.read_text() if path.exists() else f"# Benchmark results\n\n{BEGIN}\n{END}\n"
	pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
	text = pattern.sub(lambda match: f"{BEGIN}\n\n{generated}\n\n{END}", text)
	path.write_text(text)


def charts(results, png_dir, svg_dir=None):
	"""Click latency by round trip, and page weight and memory per tab."""

	try:
		import matplotlib
		matplotlib.use("Agg")
		import matplotlib.pyplot as plt
	except ImportError:
		print("matplotlib isn't installed: no charts")
		return []

	plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False,
		"axes.edgecolor": "#8a8984", "axes.labelcolor": "#52514e", "xtick.color": "#52514e", "ytick.color": "#52514e",
		"axes.titlecolor": "#0b0b0b", "figure.facecolor": "#fcfcfb", "axes.facecolor": "#fcfcfb", "svg.fonttype": "none"})
	fw = results["frameworks"]
	names = list(fw)
	written = []

	def save(figure, stem):
		png_dir.mkdir(parents=True, exist_ok=True)
		figure.savefig(png_dir / f"bench-{stem}.png", dpi=150, bbox_inches="tight")
		written.append(png_dir / f"bench-{stem}.png")
		if svg_dir:
			figure.savefig(svg_dir / f"{stem}.svg", bbox_inches="tight")
			written.append(svg_dir / f"{stem}.svg")
		plt.close(figure)

	def bars(axis, groups, values, ylabel, title, fmt="{:.0f}"):
		width = 0.8 / len(names)
		for i, name in enumerate(names):
			xs = [g + (i - (len(names) - 1) / 2) * width for g in range(len(groups))]
			ys = values[name]
			axis.bar(xs, [y or 0 for y in ys], width * 0.9, color=COLORS[i % len(COLORS)], label=fw[name]["label"])
			for x, y in zip(xs, ys):
				if y is not None:
					axis.annotate(fmt.format(y), (x, y), ha="center", va="bottom", fontsize=7, color="#52514e",
						xytext=(0, 2), textcoords="offset points")
		axis.set_xticks(range(len(groups)), groups)
		axis.set_ylabel(ylabel)
		axis.set_title(title, loc="left", fontsize=11)
		axis.grid(axis="y", color="#e4e3df", linewidth=0.6)
		axis.set_axisbelow(True)

	# 1. Click latency
	rtts = sorted({rtt for name in names for rtt in fw[name].get("interactions", {})}, key=int)
	if rtts:
		figure, axes = plt.subplots(1, 3, figsize=(14, 4.2), sharey=True)
		for axis, (kind, title) in zip(axes, (("counter", "Counter +1 (UI state)"), ("toggle", "Todo toggle (server data)"),
				("add", "Todo add (server-confirmed)"))):
			values = {name: [(fw[name]["interactions"].get(rtt, {}).get(kind) or {}).get("median") for rtt in rtts] for name in names}
			bars(axis, [f"{rtt} ms RTT" for rtt in rtts], values, "ms, median" if kind == "counter" else "", title)
		axes[0].legend(frameon=False, fontsize=8, loc="upper left")
		figure.suptitle("Click → DOM updated, by network round trip (lower is better)", x=0.01, ha="left", fontsize=12)
		save(figure, "latency")

	# 2. Page weight (todo app) and memory per tab: two charts, one measure each
	if any("page_weight" in fw[name] for name in names):
		figure, axes = plt.subplots(1, 2, figsize=(12, 4))
		apps = ["counter", "todo", "chat"]
		values = {name: [((fw[name].get("page_weight", {}).get(app) or {}).get("gzip_bytes") or {}).get("median", 0) / 1000
			for app in apps] for name in names}
		bars(axes[0], ["Counter", "Todo (1,000 items)", "Chat"], values, "KB (HTTP bodies, gzip -6)", "Page weight, cold load")
		counts = sorted({count for name in names for count in fw[name].get("idle_memory", {})}, key=int)
		if counts:
			values = {name: [(fw[name].get("idle_memory", {}).get(count) or {}).get("per_tab_kb") for count in counts] for name in names}
			bars(axes[1], [f"{count} tabs" for count in counts], values, "KB per tab", "Server memory per idle connected tab")
		axes[0].legend(frameon=False, fontsize=8, loc="upper left")
		save(figure, "weight-memory")

	return written
